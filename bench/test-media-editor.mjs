import assert from 'node:assert/strict';
import { parseEditorProject, validateEditorOwnership, editorMediaItems } from '../src/lib/media-editor/project.ts';
import { imageGeometry } from '../src/lib/media-editor/image-export.ts';
const url=n=>`https://test.public.blob.vercel-storage.com/inst-acessor/alice/${n}.jpg`;
const slide=n=>({id:String(n),originalUrl:url(n),exportedUrl:url(`derived-${n}`),type:'image',framing:{zoom:1,offsetX:0,offsetY:0},rotation:0,brightness:1,contrast:1});
const project={version:1,kind:'media-editor',aspectRatio:'4:5',slides:[slide(2),slide(1)]};
let count=0;const ok=(value)=>{assert.ok(value);count++;};
ok(parseEditorProject(JSON.stringify(project)));
ok(validateEditorOwnership(project,'alice'));ok(!validateEditorOwnership(project,'bob'));
assert.deepEqual(editorMediaItems(project).map(s=>s.url),[url('derived-2'),url('derived-1')]);count++;
ok(!parseEditorProject(JSON.stringify({...project,slides:Array.from({length:8},(_,i)=>slide(i))})));
ok(!parseEditorProject(JSON.stringify({...project,slides:[slide(1),slide(1)]})));
ok(!parseEditorProject(JSON.stringify({...project,slides:[{...slide(1),brightness:Infinity}]})));
ok(!parseEditorProject('x'.repeat(65537)));ok(!parseEditorProject('{bad'));
ok(!validateEditorOwnership({...project,slides:[{...slide(1),exportedUrl:'https://127.0.0.1/private'}]},'alice'));
ok(!validateEditorOwnership({...project,videoProject:JSON.stringify({version:1})},'alice'));
const a=imageGeometry(200,100,100,100,0,1);assert.equal(a.width,200);assert.equal(a.height,100);count++;
const b=imageGeometry(200,100,100,100,90,1);ok(Math.abs(b.height-100)<0.0001);
ok(imageGeometry(200,100,100,100,0,2).width===400);
console.log(`${count} media editor assertions passed; Canvas export requires browser verification.`);
